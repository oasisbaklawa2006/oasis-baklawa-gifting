type SeedInput = {
  slug: string;
  name: string;
  categoryCue: string;
  categoryId: string;
  collectionIds?: string[];
  shortDescription: string;
  description: string;
  ingredients?: string[];
  allergens?: string[];
  occasions?: string[];
  badges?: Product["badges"];
  variants: { label: string; amount: number }[];
  image: { src: string; alt: string };
};

const seed = (input: SeedInput): ProductSeed => ({
  id: `p-${input.slug}`,
  slug: input.slug,
  name: input.name,
  categoryCue: input.categoryCue,
  categoryId: input.categoryId,
  collectionIds: input.collectionIds ?? [],
  shortDescription: input.shortDescription,
  description: input.description,
  ingredients: input.ingredients ?? ["Ingredient declaration pending"],
  allergens: input.allergens ?? ["Declaration pending — may contain nuts, milk and wheat"],
  storage: "Store in a cool, dry place away from direct sunlight.",
  shelfLife: "Refer to the date printed on the pack.",
  leadTime: "Dispatch timeline confirmed at checkout.",
  occasions: input.occasions ?? [],
  dietary: [],
  verifiedClaims: [],
  isMock: true,
  badges: input.badges ?? [],
  details: [],
  variants: input.variants.map((v, i) => ({
    id: `v-${i + 1}`,
    label: v.label,
    price: inr(v.amount),
    availability: "in-stock" as const,
  })),
  image: input.image,
});

